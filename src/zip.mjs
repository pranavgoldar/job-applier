// A minimal ZIP writer (stored, no compression) so the browser extension can be
// offered as one download without adding a dependency.
import fs from "node:fs";
import path from "node:path";
import { crc32 } from "node:zlib";
export function zip(files) {
  const parts = [],
    central = [];
  let offset = 0;
  for (const { name, data } of files) {
    const nameBytes = Buffer.from(name),
      crc = crc32(data),
      local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4); // version needed
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt32LE(0x00210000, 10); // fixed time and date (1980-01-01)
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBytes.length, 26);
    parts.push(local, nameBytes, data);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4);
    entry.writeUInt16LE(20, 6);
    entry.writeUInt16LE(0x0800, 8);
    entry.writeUInt32LE(0x00210000, 12);
    entry.writeUInt32LE(crc, 16);
    entry.writeUInt32LE(data.length, 20);
    entry.writeUInt32LE(data.length, 24);
    entry.writeUInt16LE(nameBytes.length, 28);
    entry.writeUInt32LE(offset, 42);
    central.push(entry, nameBytes);
    offset += 30 + nameBytes.length + data.length;
  }
  const directory = Buffer.concat(central),
    end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, directory, end]);
}
export function extensionZip(
  dir = new URL("../extension/", import.meta.url),
  folder = "career-os-extension",
) {
  return zip(
    fs
      .readdirSync(dir)
      .filter((n) => !n.startsWith("."))
      .sort()
      .map((n) => ({
        name: path.posix.join(folder, n),
        data: fs.readFileSync(new URL(n, dir)),
      })),
  );
}
